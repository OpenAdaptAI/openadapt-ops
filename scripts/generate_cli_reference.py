"""Generate the launcher and agent command help from the pinned releases.

Run it with Python 3.12 in an environment that has exactly the versions in
`cli-reference/requirements.txt` installed:

    uv venv --python 3.12 /tmp/cli-ref
    uv pip install --python /tmp/cli-ref/bin/python -r cli-reference/requirements.txt
    /tmp/cli-ref/bin/python scripts/generate_cli_reference.py

It writes, from each program's own parser:

- `docs/reference/cli-help.md`: the `--help` text of every `openadapt` and
  `openadapt agent` command.
- `tests/fixtures/agent_cli.json`: each agent subcommand's long options, which
  the tests check documented agent commands against.

Flow's commands come from `scripts/flow_cli_reference.py` instead. The Flow
pin here only has to match its `FLOW_VERSION`, since the agent runs on Flow.

The CI job `cli-reference` reruns it and fails when the committed files
differ, so the reference can't drift from the pinned releases.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "cli-reference" / "requirements.txt"
PAGE = ROOT / "docs" / "reference" / "cli-help.md"
FIXTURES = ROOT / "tests" / "fixtures"
WIDTH = "100"
# Research commands the launcher still carries. The docs cover the product
# path only, so their help stays out of the reference.
LAUNCHER_RESEARCH = {"capture", "eval", "serve", "train"}


def pinned_versions(path: Path = REQUIREMENTS) -> dict[str, str]:
    """Return {distribution: version} from `name==version` lines."""
    pins: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        name, sep, version = line.partition("==")
        if not sep:
            raise SystemExit(f"{path}: pin every package with ==: {line!r}")
        pins[name.strip()] = version.strip()
    return pins


def _check_installed(pins: dict[str, str]) -> None:
    wrong = []
    for name, version in pins.items():
        try:
            installed = metadata.version(name)
        except metadata.PackageNotFoundError:
            installed = None
        if installed != version:
            wrong.append(f"{name}: pinned {version}, installed {installed}")
    if wrong:
        raise SystemExit("Install the pinned versions first:\n  " + "\n  ".join(wrong))
    if sys.version_info[:2] != (3, 12):
        raise SystemExit("Run with Python 3.12; help formatting differs between versions")


def _walk_argparse(parser: argparse.ArgumentParser, path: list[str], out: list):
    """Append (path, help text, long options) for the parser and its subcommands."""
    options = sorted(
        option
        for action in parser._actions
        for option in action.option_strings
        if option.startswith("--")
    )
    out.append((path, parser.format_help(), options))
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for name, sub in action.choices.items():
                _walk_argparse(sub, path + [name], out)


def _walk_click(command, path: list[str], out: list) -> None:
    import click

    with click.Context(command, info_name=" ".join(path)) as ctx:
        out.append((path, command.get_help(ctx) + "\n", []))
    if isinstance(command, click.Group):
        for name in sorted(command.commands):
            sub = command.commands[name]
            if sub.hidden or (path == ["openadapt"] and name in LAUNCHER_RESEARCH):
                continue
            _walk_click(sub, path + [name], out)


def collect() -> dict[str, list]:
    os.environ["COLUMNS"] = WIDTH
    from openadapt.cli import main as launcher
    from openadapt_agent.cli import build_parser as agent_parser

    programs: dict[str, list] = {"openadapt": [], "openadapt-agent": []}
    _walk_click(launcher, ["openadapt"], programs["openadapt"])
    _walk_argparse(agent_parser(), ["openadapt-agent"], programs["openadapt-agent"])
    return programs


def render_page(pins: dict[str, str], programs: dict[str, list]) -> str:
    versions = ", ".join(f"{name} {version}" for name, version in pins.items())
    lines = [
        "---",
        "description: >-",
        "  The --help text of every openadapt and openadapt agent command in the",
        "  released versions, generated from each program's parser.",
        "---",
        "",
        "# Launcher and agent command help",
        "",
        "<!-- Generated by scripts/generate_cli_reference.py. Don't edit by hand. -->",
        "",
        f"This page is the `--help` text of every `openadapt` and `openadapt agent`",
        f"command, from {versions}. It's generated from each program's parser, and",
        "CI fails when it differs from those versions. [Commands](cli.md) explains",
        "what each command is for, and [All Flow commands](flow-commands.md) lists",
        "the `openadapt flow` commands. The launcher's research commands",
        "(`capture`, `eval`, `serve`, and `train`) aren't listed.",
        "",
        "`openadapt agent ...` runs `openadapt-agent ...`; the help text uses the",
        "second name.",
        "",
    ]
    titles = {
        "openadapt": "openadapt",
        "openadapt-agent": "openadapt agent",
    }
    for program, entries in programs.items():
        lines += [f"## {titles[program]}", ""]
        for path, text, _ in entries:
            lines += [f"### `{' '.join(path)}`", "", "```text", text.rstrip("\n"), "```", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def fixture(program: str, version: str, entries: list) -> str:
    root, *_ = entries
    commands = {
        " ".join(path[1:]): options for path, _, options in entries[1:]
    }
    data = {
        "program": program,
        "version": version,
        "source": f"argparse parser of {program} {version}, long options only. "
        "Generated by scripts/generate_cli_reference.py.",
        "global_options": root[2],
        "commands": dict(sorted(commands.items())),
    }
    return json.dumps(data, indent=2, sort_keys=False) + "\n"


def main() -> int:
    pins = pinned_versions()
    _check_installed(pins)
    programs = collect()
    PAGE.write_text(render_page(pins, programs), encoding="utf-8")
    (FIXTURES / "agent_cli.json").write_text(
        fixture("openadapt-agent", pins["openadapt-agent"], programs["openadapt-agent"]),
        encoding="utf-8",
    )
    print(f"Wrote {PAGE.relative_to(ROOT)} and the agent CLI fixture")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
